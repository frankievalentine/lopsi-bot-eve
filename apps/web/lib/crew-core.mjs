/**
 * The crew list's rules, shared by `pnpm crew` (scripts/crew.mjs, from files on
 * disk) and the dashboard's change requests (lib/config-changes.ts, from files
 * in the GitHub repository), so both produce the same crew.generated.ts byte
 * for byte.
 *
 * @packageDocumentation
 */

import { z } from "zod";

export const MASCOTS = /** @type {const} */ ([
  "skipper",
  "lookout",
  "purser",
  "navigator",
  "deckhand",
  "signal",
]);

/** The `$schema` every crew.json points at, relative to agents/<name>/. */
export const CREW_SCHEMA_PATH = "../../scripts/crew.schema.json";

export const CrewSchema = z
  .object({
    $schema: z.string().optional(),
    // Which connectors (apps/web/lib/connectors.json ids) the member may use; absent is all of them.
    connectors: z
      .array(z.string().regex(/^[a-z][a-z0-9-]{0,30}$/u))
      .max(30)
      .optional(),
    mascot: z.enum(MASCOTS),
    name: z.string().trim().min(1).max(40),
    order: z.number().int().min(0).optional(),
    role: z.string().trim().max(80).optional(),
    suggestions: z.array(z.string().trim().min(1).max(120)).max(4).optional(),
  })
  .strict();

/** A crew directory name: lowercase letters, digits and hyphens, as an eve route segment. */
export const CREW_ID = /^[a-z][a-z0-9-]{0,39}$/u;

/**
 * Parses one crew.json's text.
 *
 * @param {string} text
 * @returns {{ ok: true, data: z.infer<typeof CrewSchema> } | { ok: false, error: string }}
 */
export function parseCrewJson(text) {
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    return { error: "isn't valid JSON", ok: false };
  }
  const parsed = CrewSchema.safeParse(json);
  return parsed.success
    ? { data: parsed.data, ok: true }
    : { error: z.prettifyError(parsed.error), ok: false };
}

/**
 * A crew.json's text, as the dashboard writes it: `$schema` first, then the
 * fields in a fixed order, two-space indented, with a trailing newline.
 *
 * @param {z.infer<typeof CrewSchema>} data
 * @returns {string}
 */
export function serializeCrewJson(data) {
  const { connectors, mascot, name, order, role, suggestions } = data;
  return `${JSON.stringify(
    {
      $schema: CREW_SCHEMA_PATH,
      name,
      ...(role ? { role } : {}),
      mascot,
      ...(order === undefined ? {} : { order }),
      ...(suggestions?.length ? { suggestions } : {}),
      ...(connectors === undefined ? {} : { connectors }),
    },
    null,
    2
  )}\n`;
}

/**
 * The generated crew list's source from each agent directory's crew.json data
 * (`undefined` when it has none).
 *
 * @param {ReadonlyArray<{ id: string, data: z.infer<typeof CrewSchema> | undefined }>} entries
 * @returns {string}
 */
export function crewSource(entries) {
  const crew = [...entries]
    .sort((a, b) => (a.id < b.id ? -1 : Number(a.id > b.id)))
    .map(({ data, id }, index) =>
      data === undefined
        ? {
            id,
            mascot: MASCOTS[index % MASCOTS.length],
            name: id,
            order: undefined,
            role: "",
            suggestions: [],
          }
        : {
            id,
            mascot: data.mascot,
            name: data.name,
            order: data.order,
            role: data.role ?? "",
            suggestions: data.suggestions ?? [],
          }
    )
    // `order` first (lowest first), then the rest by directory name. The order
    // itself isn't part of the generated list.
    .sort((a, b) => {
      if (a.order === undefined || b.order === undefined) {
        // Ordered members come first; two unordered ones keep their name order.
        return (
          (a.order === undefined ? 1 : 0) - (b.order === undefined ? 1 : 0)
        );
      }
      return a.order - b.order;
    })
    .map(({ order: _order, ...member }) => member);

  return `// Generated by scripts/crew.mjs from agents/*/crew.json. Run \`pnpm crew\` after changing them.

import type { MascotKind } from "@/components/mascot";

export interface CrewMember {
  /** The eve workspace agent: its directory under agents/ and its route prefix /eve/<id>/v1. */
  readonly id: string;
  readonly mascot: MascotKind;
  readonly name: string;
  readonly role: string;
  readonly suggestions: readonly string[];
}

export const CREW: readonly CrewMember[] = ${JSON.stringify(crew, null, 2)};
`;
}
